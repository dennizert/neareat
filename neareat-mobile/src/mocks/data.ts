function buildDetail(r: Restaurant, address: string, phone: string): RestaurantDetail {
  return {
    ...r,
    formattedAddress: address,
    formattedPhoneNumber: phone,
    openingHours: {
      open_now: r.isOpenNow ?? true,
      weekday_text: WEEKDAY_TEXT,
    },
    photos: [
      r.photoUrl!,
      `https://picsum.photos/seed/${r.placeId}b/800/400`,
      `https://picsum.photos/seed/${r.placeId}c/800/400`,
    ],
    googleReviews: SAMPLE_GOOGLE_REVIEWS,
    popularTimes: null,
  };
}

